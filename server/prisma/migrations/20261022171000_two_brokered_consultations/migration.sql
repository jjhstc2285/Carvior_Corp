-- 알선 건 두 개를 판매에서 알선으로 돌린다.
--
-- 둘 다 차량 관리에는 이미 '알선' 표가 붙어 있는데 상담 종류만 판매로 남아 있었다.
-- 그래서 '어디서 팔렸나' 그래프에서만 우리가 판 차로 세어졌다.
--
--   181주9256  SM6   26.09.14  내용에 "알선으로 다른 차량 판매완료"라고 적혀 있다
--   159오5949  G90   26.09.18
--
-- 차량번호로 찾는다. 아이디로 박으면 무엇을 고친 건지 나중에 읽을 수 없다.
-- 지금은 화면(상담 수정)에서도 종류를 바꿀 수 있다 — 이건 쌓여 있던 두 건을 맞추는 것뿐이다.
UPDATE `Consultation`
   SET `kind` = 'BROKERAGE'
 WHERE `kind` = 'SALE'
   AND REPLACE(`vehicleNumber`, ' ', '') IN ('181주9256', '159오5949');

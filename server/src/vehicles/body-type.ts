export function inferBodyType(vehicleName: string): VehicleBodyType {
  const name = vehicleName.toUpperCase();
  for (const [type, words] of KEYWORDS) {
    if (words.some((w) => name.includes(w.toUpperCase()))) return type;
  }
  return VehicleBodyType.OTHER;
}
